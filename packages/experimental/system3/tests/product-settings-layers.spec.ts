/**
 * Desktop and Web product settings layering: the `system3` and `continuum-memory` rows come from profile bundles, so a
 * settings write in the profile patch survives the product's command-line overlay, across releases' bundle lists.
 */
import { execFile } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { promisify } from 'node:util'
import { pathToFileURL } from 'node:url'
import type { EntryOptions } from '@deepseek-ai/cordis-plugin-loader'
import { composeEntries, loadOverlayPatches, readProfilePatches, type ProfileContext } from '@deepseek-ai/dsh-app-boot'
import { describe, expect, it, onTestFinished } from 'vitest'

const BASE = ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app']
const JEV = '@deepseek-ai/dsh-experimental-apus-dsh-jev-plugin', SYSTEM3 = '@deepseek-ai/dsh-experimental-system3'
const CONTINUUM = '@deepseek-ai/dsh-experimental-continuum-jev', REFLEX_LOCAL = '@deepseek-ai/dsh-experimental-reflex-local-bundle'
/** Bundle lists the launchers write: frontend `generation-launch.ts` and `scripts/product-web-launch.mjs`. */
const SURFACES = {
  Desktop: [...BASE, JEV, SYSTEM3, CONTINUUM, REFLEX_LOCAL],
  Web: [...BASE, JEV, SYSTEM3, CONTINUUM],
} as const

function flatten(rows: readonly EntryOptions[]): EntryOptions[] {
  return rows.flatMap(row => [row, ...row.group && Array.isArray(row.config) ? flatten(row.config as EntryOptions[]) : []])
}

/** The overlay each surface passes with `--patch`, generated by the product scripts. */
async function overlay(surface: keyof typeof SURFACES, home: string): Promise<string> {
  const path = join(home, 'product.patch.yml')
  if (surface === 'Desktop') {
    const generator = pathToFileURL(resolve('frontend/scripts/generate-system3-patch.mjs')).href
    await promisify(execFile)(process.execPath, ['--input-type=module', '-e',
      `import { generateSystem3Patch } from ${JSON.stringify(generator)}; await generateSystem3Patch(${JSON.stringify(home)});`])
    writeFileSync(path, readFileSync(join(home, 'desktop.patch.yml')))
  } else {
    const collector = pathToFileURL(resolve('scripts/product-web-package.mjs')).href
    const { stdout } = await promisify(execFile)(process.execPath, ['--input-type=module', '-e',
      `import { webProfilePatch } from ${JSON.stringify(collector)}; process.stdout.write(webProfilePatch);`])
    writeFileSync(path, stdout)
  }
  return path
}

/** A `web` profile with the given bundles under the shipped CLI install, launched with the surface overlay. */
async function product(surface: keyof typeof SURFACES, bundles: readonly string[]) {
  const home = realpathSync(mkdtempSync(join(tmpdir(), 'product-settings-')))
  onTestFinished(() => { rmSync(home, { recursive: true, force: true }) })
  const dir = join(home, 'profiles', 'web')
  mkdirSync(dir, { recursive: true })
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ dsh: { profile: { bundles } } }))
  const profile: ProfileContext = { name: 'web', startedBundles: bundles, dir, patchPath: join(dir, 'cordis.patch.yml'),
    installAnchor: resolve('apps/cli/package.json'), cwd: home, home, overlays: loadOverlayPatches('test', await overlay(surface, home)),
    telemetryDisabledEnv: undefined }
  const rows = (): EntryOptions[] => flatten(composeEntries([readProfilePatches('test', profile)]))
  return {
    rows,
    /**
     * Append the row `ConfigEditor.edit` appends to the profile patch and return the composed config, which the editor
     * requires to equal the written one.
     */
    write: (id: string, change: (current: Record<string, unknown>) => Record<string, unknown>) => {
      const row = rows().find(entry => entry.id === id) as EntryOptions
      const next = change(row.config as Record<string, unknown>)
      writeFileSync(profile.patchPath, JSON.stringify([{ id, name: row.name, config: next }]))
      return { written: next, composed: rows().find(entry => entry.id === id)?.config as Record<string, unknown> | undefined }
    },
  }
}

const bundleConfig = (): Record<string, unknown> | undefined => loadOverlayPatches('test', resolve('packages/experimental/system3/cordis.patch.yml'))
  .flatMap(patch => patch.insert ?? []).find(row => row.id === 'system3')?.config as Record<string, unknown> | undefined

describe.each(Object.keys(SURFACES) as Array<keyof typeof SURFACES>)('%s product profile', (surface) => {
  it('composes one bundle-owned System3 row whose settings writes persist, like Continuum memory', async () => {
    const { rows, write } = await product(surface, SURFACES[surface])
    expect(rows().filter(row => row.id === 'system3')).toEqual([expect.objectContaining({ config: bundleConfig() })])
    const frontLoaded = write('system3', current => ({ ...current, frontLoadedDecisions: false }))
    expect(frontLoaded.composed).toEqual(frontLoaded.written)
    const memory = write('continuum-memory', current => ({ ...current, enabled: true }))
    expect(memory.composed).toEqual(memory.written)
  })

  it('upgrades a profile from a release without the System3 bundle to exactly one System3 row', async () => {
    const earlier = SURFACES[surface].filter(name => name !== SYSTEM3)
    const { rows } = await product(surface, [...earlier, SYSTEM3])
    const system3 = rows().filter(row => row.id === 'system3')
    expect(system3).toHaveLength(1)
    expect(system3[0]?.config).toEqual(bundleConfig())
    expect(rows().filter(row => row.id === 'ui-system3')).toHaveLength(1)
  })
})
